static const double PI_D = 3.14159265358979323846;

static Ref<Resource> load_res(const String &p_path) {
	return ResourceLoader::get_singleton()->load(p_path);
}

// MeshBuilder (GDScript, the world's mesh maker): made through its script
static Ref<RefCounted> new_builder() {
	static Ref<Script> script;
	if (script.is_null()) {
		script = load_res("res://systems/world_gen/mesh_builder.gd");
	}
	return script->call("new");
}

