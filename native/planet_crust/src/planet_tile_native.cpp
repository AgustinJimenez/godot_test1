PlanetTile::PlanetTile() {
	origin.resize(3);
	origin.fill(0.0);
}

Array PlanetTile::faces() {
	PackedVector3Array all = PlanetNoise::cube_faces();
	Array result;
	for (int face_index = 0; face_index < 6; face_index++) {
		Array axes;
		axes.append(all[face_index * 3]);
		axes.append(all[face_index * 3 + 1]);
		axes.append(all[face_index * 3 + 2]);
		result.append(axes);
	}
	return result;
}

// The ground shader material (made once, shared by every tile).
Ref<ShaderMaterial> PlanetTile::ground_material() {
	static Ref<ShaderMaterial> material;
	if (material.is_null()) {
		Ref<ShaderMaterial> made;
		made.instantiate();
		made->set_shader(load_res("res://shaders/world/planet_ground.gdshader"));
		OS *os = OS::get_singleton();
		if (os->has_environment("PLANET_FORCE_SCAN")) { // (a test: which soil scan shows everywhere)
			made->set_shader_parameter("force_scan", os->get_environment("PLANET_FORCE_SCAN").to_int());
		}
		if (os->has_environment("PLANET_GROUND_OFF")) { // (a tool: scripts/gpu_ground_breakdown.sh)
			made->set_shader_parameter("cost_off", os->get_environment("PLANET_GROUND_OFF").to_int());
		}
		// real surface detail (generated by scripts/make_ground_textures.py): normal + brightness
		made->set_shader_parameter("rock_map", load_res("res://assets/textures/ground/rock.png"));
		made->set_shader_parameter("soil_map", load_res("res://assets/textures/ground/soil.png"));
		made->set_shader_parameter("sand_map", load_res("res://assets/textures/ground/sand.png"));
		// scans of real ground for the near detail (CC0, ambientCG): see assets/textures/ground/scans/README.md
		made->set_shader_parameter("cliff_c", load_res("res://assets/textures/ground/scans/cliff_c.png"));
		made->set_shader_parameter("cliff_n", load_res("res://assets/textures/ground/scans/cliff_n.png"));
		for (const char *scan : { "gravel", "red", "leaf" }) {
			made->set_shader_parameter(String("scan_%s_c") % String(scan), load_res(String("res://assets/textures/ground/scans/%s_c.png") % String(scan)));
			made->set_shader_parameter(String("scan_%s_n") % String(scan), load_res(String("res://assets/textures/ground/scans/%s_n.png") % String(scan)));
		}
		material = made;
	}
	return material;
}

// The water shader material (made once, shared by every tile).
Ref<ShaderMaterial> PlanetTile::water_material() {
	static Ref<ShaderMaterial> material;
	if (material.is_null()) {
		Ref<ShaderMaterial> made;
		made.instantiate();
		made->set_shader(load_res("res://shaders/world/planet_water.gdshader"));
		made->set_shader_parameter("depth_fade", 24.0); // the shelf shows as it deepens
		material = made;
	}
	return material;
}

// The river shader material (made once, shared by every tile).
Ref<ShaderMaterial> PlanetTile::river_material() {
	static Ref<ShaderMaterial> material;
	if (material.is_null()) {
		Ref<ShaderMaterial> made;
		made.instantiate();
		made->set_shader(load_res("res://shaders/world/river.gdshader"));
		made->set_render_priority(1); // where water meets water, the river is drawn last
		material = made;
	}
	return material;
}

// The tile key: (face, level, x, y) packed in one int.
int64_t PlanetTile::key_of(int64_t p_f, int64_t p_lvl, int64_t p_x, int64_t p_y) {
	return (((p_f * 32 + p_lvl) << 40) | (p_x << 20)) | p_y;
}

// Direction on the planet of the cube face point (s, t), both -1..1.
Vector3 PlanetTile::direction(int64_t p_f, double p_s, double p_t) {
	PackedVector3Array all = PlanetNoise::cube_faces();
	double a = std::tan(p_s * PI_D * 0.25);
	double b = std::tan(p_t * PI_D * 0.25);
	Vector3 v = all[p_f * 3] + all[p_f * 3 + 1] * a + all[p_f * 3 + 2] * b;
	return v.normalized();
}

// Builds the tile (on any thread). `collide`: also build the collider (the player walks here).
PlanetTile *PlanetTile::build(int64_t p_f, int64_t p_lvl, int64_t p_x, int64_t p_y, const Ref<PlanetNoise> &p_noise, bool p_collide) {
	tile_key = key_of(p_f, p_lvl, p_x, p_y);
	face = p_f;
	level = p_lvl;
	tile_x = p_x;
	tile_y = p_y;
	noise_ = p_noise;
	settings_ = p_noise->get_settings();
	double radius = settings_->get_radius();
	int64_t count = (int64_t)1 << level;
	double s0 = -1.0 + 2.0 * (double)p_x / (double)count;
	double s1 = -1.0 + 2.0 * (double)(p_x + 1) / (double)count;
	double t0 = -1.0 + 2.0 * (double)p_y / (double)count;
	double t1 = -1.0 + 2.0 * (double)(p_y + 1) / (double)count;
	centre = direction(p_f, (s0 + s1) * 0.5, (t0 + t1) * 0.5);
	origin = PackedFloat64Array();
	origin.append(centre.x * radius);
	origin.append(centre.y * radius);
	origin.append(centre.z * radius);
	PackedVector3Array all_faces = PlanetNoise::cube_faces();
	Vector3 u = all_faces[p_f * 3 + 1];
	e1 = (u - centre * u.dot(centre)).normalized();
	e3 = e1.cross(centre);
	local_basis = Basis(e1, centre, e3);
	size = (direction(p_f, s0, (t0 + t1) * 0.5) - direction(p_f, s1, (t0 + t1) * 0.5)).length() * radius;
	set_name(vformat("Tile_%d_%d_%d_%d", p_f, p_lvl, p_x, p_y));
	int cells = (int)settings_->get_tile_cells();
	Ref<PlanetCrustNative> crust = noise_->get_native();
	// padded grid of local positions (one extra ring round the tile, for the edge normals)
	PackedVector3Array packed_dirs = crust->tile_dirs((int)p_f, s0, s1, t0, t1, cells);
	PackedFloat32Array heights = noise_->heights_of(packed_dirs); // (the crust is asked for the whole grid at once)
	PackedVector3Array packed_positions = crust->tile_positions((int)p_f, s0, s1, t0, t1, cells, heights, origin, e1, centre, e3);
	min_height = crust->tile_min_height(heights, cells);
	PackedVector3Array packed_normals = crust->grid_normals(packed_positions, cells);
	PackedColorArray packed_colours = crust->ground_colours(packed_dirs, heights, packed_normals, cells);
	Ref<RefCounted> builder = new_builder();
	PackedByteArray materials = crust->ground_materials(packed_dirs, heights, packed_normals, cells);
	Dictionary made = crust->triangles(packed_positions, packed_normals, packed_colours, cells, p_collide ? 0.0 : skirt_drop(), materials);
	builder->call("append_smooth", made["vertices"], made["normals"], made["colours"], made["custom"], made.get("custom1", PackedByteArray()),
			made.get("custom2", PackedByteArray()), made.get("morph", PackedFloat32Array()));
	PackedVector3Array faces_found = made["faces"];
	MeshInstance3D *mesh_instance = memnew(MeshInstance3D);
	mesh_instance->set_mesh(builder->call("commit"));
	mesh_instance->set_material_override(ground_material());
	set_morph(mesh_instance);
	ground_instance_id = mesh_instance->get_instance_id(); // (PlanetShells copies it)
	if (!p_collide && level < settings_->max_level() - 1) {
		mesh_instance->set_cast_shadows_setting(GeometryInstance3D::SHADOW_CASTING_SETTING_OFF);
	}
	add_child(mesh_instance);
	if (level >= settings_->max_level() - 6) {
		add_occluder(packed_positions, cells);
	}
	if (settings_->get_sea_on() && min_height < settings_->get_sea_level() + 0.5) {
		add_sea(packed_dirs, cells);
	}
	add_crust_rivers(packed_dirs, heights);
	if (level >= settings_->max_level() - 4) { // plants can grow here later (PlanetSurface asks for them)
		plant_grid = Dictionary();
		plant_grid["positions"] = Array(); // (the script fallbacks that read them are gone)
		plant_grid["dirs"] = Array();
		plant_grid["heights"] = heights;
		plant_grid["packed_positions"] = packed_positions;
		plant_grid["packed_dirs"] = packed_dirs;
	}
	if (p_collide) {
		has_collider = true;
		StaticBody3D *body = memnew(StaticBody3D);
		body->set_collision_layer(1);
		CollisionShape3D *collision = memnew(CollisionShape3D);
		Ref<ConcavePolygonShape3D> shape;
		shape.instantiate();
		shape->set_faces(faces_found);
		collision->set_shape(shape);
		body->add_child(collision);
		add_child(body);
	}
	return this;
}

// Geomorphing: this tile is shown until the player is 2 * split_factor tile widths away (then the tile twice as big takes its place). Over the
// last tile width before that its vertices slide to where that bigger tile has its surface (the vertex shader reads `lod_morph` and the CUSTOM3
// of each vertex), so the ground does not jump when a tile is swapped. Top tiles have no bigger one.
void PlanetTile::set_morph(MeshInstance3D *p_instance) const {
	if (level == 0) {
		return;
	}
	double end = 2.0 * settings_->get_split_factor() * size - 0.75 * size;
	p_instance->set_instance_shader_parameter("lod_morph", Vector2(end - size, end));
}

// Plants this tile (on any thread): a node full of plants for `detail`, not yet in the tree.
Node3D *PlanetTile::grow_plants(int64_t p_detail) {
	Node3D *holder = memnew(Node3D);
	holder->set_name(vformat("PlantsOf%d", tile_key));
	Ref<PlanetScatter> scatter;
	scatter.instantiate();
	scatter->populate(holder, tile_key, noise_, plant_grid, settings_->get_tile_cells(), size, p_detail, has_collider);
	return holder;
}

// How far the skirt round a tile hangs: deep enough to hide the crack between this tile and a finer neighbour, no deeper.
double PlanetTile::skirt_drop() const {
	return CLAMP(size * 0.03, 2.0, noise_->get_relief() * 0.15 + 4.0);
}

// A coarse copy of the ground, sunk below it, for occlusion culling (a hill hides the plants and rocks behind it).
void PlanetTile::add_occluder(const PackedVector3Array &p_positions, int p_cells) {
	Dictionary made = noise_->get_native()->tile_occluder(p_positions, p_cells, skirt_drop());
	// the tile is built on a worker thread but the rendering server is fed from the main thread only: the occluder is made there
	call_deferred("make_occluder", made["vertices"], made["indices"]);
}

void PlanetTile::make_occluder(const PackedVector3Array &p_vertices, const PackedInt32Array &p_indices) {
	Ref<ArrayOccluder3D> occluder;
	occluder.instantiate();
	occluder->set_arrays(p_vertices, p_indices);
	OccluderInstance3D *instance = memnew(OccluderInstance3D);
	instance->set_occluder(occluder);
	add_child(instance);
}

void PlanetTile::add_water_mesh(Object *p_builder, const Ref<ShaderMaterial> &p_material) {
	if ((int64_t)p_builder->call("triangle_count") == 0) {
		return;
	}
	MeshInstance3D *mesh_instance = memnew(MeshInstance3D);
	mesh_instance->set_mesh(p_builder->call("commit"));
	mesh_instance->set_material_override(p_material);
	mesh_instance->set_cast_shadows_setting(GeometryInstance3D::SHADOW_CASTING_SETTING_OFF);
	add_child(mesh_instance);
}

// The sea over this tile: a coarse patch at sea level, bent like the ground.
void PlanetTile::add_sea(const PackedVector3Array &p_dirs, int p_cells) {
	Dictionary made = noise_->get_water_native()->sea_mesh(p_dirs, p_cells, size, settings_->get_radius(), settings_->get_sea_level(), origin, e1, centre, e3);
	Ref<RefCounted> builder = new_builder();
	builder->call("append_water", made["vertices"], made["normals"], made["colours"]);
	add_water_mesh(builder.ptr(), water_material());
}

// The rivers of the crust's own valleys (the drainage): the native crust says, for every corner of the tile's grid, the water level of the river
// whose valley is there; where the ground is under it (and above the sea) the corner is wet, and a square with a wet corner gets water.
void PlanetTile::add_crust_rivers(const PackedVector3Array &p_dirs, const PackedFloat32Array &p_heights) {
	if (!settings_->get_hydrology_on() || noise_->get_drainage().is_null() || level < settings_->max_level() - 3) {
		return;
	}
	PackedVector3Array samples = noise_->get_native()->river_waters(p_dirs);
	int cells = (int)settings_->get_tile_cells();
	Dictionary made = noise_->get_water_native()->river_mesh(p_dirs, p_heights, samples, cells, settings_->get_radius(), settings_->get_sea_level(), origin, e1, centre, e3);
	Ref<RefCounted> builder = new_builder();
	builder->call("append_water", made["vertices"], made["normals"], made["colours"], made.get("uvs", PackedVector2Array()));
	add_water_mesh(builder.ptr(), river_material());
}
