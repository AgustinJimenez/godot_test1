"""Writes the fitted soil generators as systems/world_gen/soil_fits.gd (the game bakes the ground scan from them).

Usage: python export_soil.py <folder with the photos> <out .gd> <name:tile_m> ...   (reads fits/<name>_soilgen.json)
Also measures from the photograph: the sand colour, the red colour and how much of the ground the red lumps cover.
"""
import json
import sys

import limits  # (first)

import cv2
import numpy as np

import soil_gen as sg

NL = chr(10)
T = chr(9)


def colours_of(folder, name):
    colour = cv2.imread(f"{folder}/{name}_diff.jpg").astype(np.float32)[:, :, ::-1] / 255.0
    flat = cv2.resize(colour, (256, 256), interpolation=cv2.INTER_AREA).reshape(-1, 3)
    redness = flat[:, 0] - 0.5 * (flat[:, 1] + flat[:, 2])
    red_mask = redness >= np.percentile(redness, 92)
    sand_mask = redness < np.percentile(redness, 40)
    middle = 0.5 * (redness[red_mask].mean() + redness[sand_mask].mean())
    return flat[sand_mask].mean(axis=0), flat[red_mask].mean(axis=0), float((redness > middle).mean())


def main():
    folder, out = sys.argv[1], sys.argv[2]
    lines = ["# Generated by tools/bark/export_soil.py from the fits in tools/bark/fits: do not edit.",
             "class_name SoilFits", "extends RefCounted", "",
             "## The fitted generators of photographed soil (parameters, height range, sand and red colours)",
             "static func fits() -> Dictionary:", T + "return {"]
    for spec in sys.argv[3:]:
        name, tile_m = spec.split(":")
        data = json.load(open(f"tools/bark/fits/{name}_soilgen.json"))
        params = {**sg.PARAMS, **data["params"]}
        h = sg._render(512, data["cm_per_px"], sg.vector(params), 1.0)
        sand, red, share = colours_of(folder, name)
        lines.append(T * 2 + '"%s": {' % name)
        lines.append(T * 3 + '"tile_cm": %.1f,' % (float(tile_m) * 100))
        lines.append(T * 3 + '"params": PackedFloat32Array([')
        for i in range(0, len(sg.KEYS), 8):
            lines.append(T * 4 + ", ".join("%.5f" % params[k] for k in sg.KEYS[i:i + 8]) + ",")
        lines.append(T * 3 + "]),")
        lines.append(T * 3 + '"height_range": Vector2(%.4f, %.4f),' % (float(h.min()), float(h.max())))
        lines.append(T * 3 + '"sand": Color(%.4f, %.4f, %.4f),' % tuple(sand))
        lines.append(T * 3 + '"red": Color(%.4f, %.4f, %.4f),' % tuple(red))
        lines.append(T * 3 + '"red_share": %.3f},' % min(max(share, 0.05), 0.5))
    lines += [T + "}", "", "", "const KEYS := ["] + [T + '"%s",' % k for k in sg.KEYS] + ["]", ""]
    open(out, "w").write(NL.join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
