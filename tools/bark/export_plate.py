"""Writes the fitted plated-bark generators as systems/world_gen/plate_fits.gd (the game bakes plated barks from them).

Usage: python export_plate.py <folder with the photos> <out .gd> <name:tile_m> ...   (reads fits/<name>_plate.json)
"""
import json
import sys

import limits  # (first)

import cv2
import numpy as np

import export_fit as ef
import plate_gen as wg

NL = chr(10)
T = chr(9)


def main():
    folder, out = sys.argv[1], sys.argv[2]
    lines = ["# Generated by tools/bark/export_plate.py from the fits in tools/bark/fits: do not edit.",
             "class_name PlateFits", "extends RefCounted", "",
             "## The fitted generators of photographed plated bark (parameters, height range, colour ramp)",
             "static func fits() -> Dictionary:", T + "return {"]
    for spec in sys.argv[3:]:
        name, tile_m = spec.split(":")
        data = json.load(open(f"tools/bark/fits/{name}_plate.json"))
        params = {**wg.PARAMS, **data["params"]}
        h = wg._render(512, data["cm_per_px"], wg.vector(params), 1.0)
        photo = cv2.imread(f"{folder}/{name}_disp.png", cv2.IMREAD_UNCHANGED).astype(np.float32)
        if photo.ndim == 3:
            photo = photo.mean(axis=2)
        photo = (photo - photo.min()) / (photo.max() - photo.min())
        ramp = ef.palette_of(folder, name, photo)
        mean_colour, gain, mottle, contrast = ef.colour_model(folder, name, photo, data["cm_per_px"])
        lift = ef.lift_of(mean_colour)
        ramp = [ef.lifted(c, lift) for c in ramp]
        lines.append(T * 2 + '"%s": {' % name)
        lines.append(T * 3 + '"tile_cm": %.1f,' % (float(tile_m) * 100))
        lines.append(T * 3 + '"params": PackedFloat32Array([')
        for i in range(0, len(wg.KEYS), 7):
            lines.append(T * 4 + ", ".join("%.5f" % params[k] for k in wg.KEYS[i:i + 7]) + ",")
        lines.append(T * 3 + "]),")
        lines.append(T * 3 + '"height_range": Vector2(%.4f, %.4f),' % (float(h.min()), float(h.max())))
        lines.append(T * 3 + '"ramp": [')
        for c in ramp:
            lines.append(T * 4 + "Color(%.4f, %.4f, %.4f)," % tuple(c))
        lines.append(T * 3 + "]},")
    lines += [T + "}", "", "", "const KEYS := ["] + [T + '"%s",' % k for k in wg.KEYS] + ["]", ""]
    open(out, "w").write(NL.join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
