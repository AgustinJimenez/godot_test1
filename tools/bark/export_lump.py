"""Writes the fitted rock-face generators as systems/world_gen/lump_fits.gd (the game bakes rock faces from them).

Usage: python export_lump.py <folder with the photos> <out .gd> <name:tile_m> ...   (reads fits/<name>_lump.json)
"""
import json
import sys

import limits  # (first)

import cv2
import numpy as np

import export_fit as ef
import lump_gen as wg

NL = chr(10)
T = chr(9)


def stains_of(folder, name):
    """Light and dark colours of the photograph and the share of dark (stained) ground: the rock's colour is these two."""
    colour = cv2.imread(f"{folder}/{name}_diff.jpg").astype(np.float32)[:, :, ::-1] / 255.0
    flat = cv2.resize(colour, (256, 256), interpolation=cv2.INTER_AREA).reshape(-1, 3)
    luma = flat @ np.array([0.2126, 0.7152, 0.0722])
    dark_mask = luma < np.percentile(luma, 30)
    light_mask = luma > np.percentile(luma, 55)
    middle = 0.5 * (luma[dark_mask].mean() + luma[light_mask].mean())
    share = float((luma < middle).mean())
    return flat[light_mask].mean(axis=0), flat[dark_mask].mean(axis=0), min(max(share, 0.05), 0.6)


def main():
    folder, out = sys.argv[1], sys.argv[2]
    lines = ["# Generated by tools/bark/export_lump.py from the fits in tools/bark/fits: do not edit.",
             "class_name LumpFits", "extends RefCounted", "",
             "## The fitted generators of photographed rock face (parameters, height range, colour ramp)",
             "static func fits() -> Dictionary:", T + "return {"]
    for spec in sys.argv[3:]:
        name, tile_m = spec.split(":")
        data = json.load(open(f"tools/bark/fits/{name}_lump.json"))
        params = {**wg.PARAMS, **data["params"]}
        h = wg._render(512, data["cm_per_px"], wg.vector(params), 1.0)
        photo = cv2.imread(f"{folder}/{name}_disp.png", cv2.IMREAD_UNCHANGED).astype(np.float32)
        if photo.ndim == 3:
            photo = photo.mean(axis=2)
        photo = (photo - photo.min()) / (photo.max() - photo.min())
        ramp = ef.palette_of(folder, name, photo)
        mean_colour, gain, mottle, contrast = ef.colour_model(folder, name, photo, data["cm_per_px"])
        lift = ef.lift_of(mean_colour)
        ramp = [ef.lifted(c, lift) for c in ramp]
        lines.append(T * 2 + '"%s": {' % name)
        lines.append(T * 3 + '"tile_cm": %.1f,' % (float(tile_m) * 100))
        lines.append(T * 3 + '"params": PackedFloat32Array([')
        for i in range(0, len(wg.KEYS), 7):
            lines.append(T * 4 + ", ".join("%.5f" % params[k] for k in wg.KEYS[i:i + 7]) + ",")
        lines.append(T * 3 + "]),")
        lines.append(T * 3 + '"height_range": Vector2(%.4f, %.4f),' % (float(h.min()), float(h.max())))
        guide = cv2.resize(photo, (16, 16), interpolation=cv2.INTER_AREA)
        lo, hi = np.percentile(guide, [2, 98])
        guide = np.clip((guide - lo) / max(hi - lo, 1e-6), 0.0, 1.0)
        lines.append(T * 3 + '"guide": PackedFloat32Array([')
        for i in range(0, 256, 8):
            lines.append(T * 4 + ", ".join("%.3f" % x for x in guide.ravel()[i:i + 8]) + ",")
        lines.append(T * 3 + "]),")
        light, dark, share = stains_of(folder, name)
        lines.append(T * 3 + '"light": Color(%.4f, %.4f, %.4f),' % tuple(light))
        lines.append(T * 3 + '"dark": Color(%.4f, %.4f, %.4f),' % tuple(dark))
        lines.append(T * 3 + '"dark_share": %.3f,' % share)
        lines.append(T * 3 + '"ramp": [')
        for c in ramp:
            lines.append(T * 4 + "Color(%.4f, %.4f, %.4f)," % tuple(c))
        lines.append(T * 3 + "]},")
    lines += [T + "}", "", "", "const KEYS := ["] + [T + '"%s",' % k for k in wg.KEYS] + ["]", ""]
    open(out, "w").write(NL.join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
