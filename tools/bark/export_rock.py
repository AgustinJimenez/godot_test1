"""Writes the fitted rock generators as a GDScript file the game bakes its rocks from.

Usage: python export_rock.py <folder with the photos> <out .gd> <name:tile_m:slot> ...
Same colour model as export_fit.py (mean colour, ramp by height, cavity gain, mottle, albedo lift).
"""
import json
import sys

import limits  # (first)

import cv2
import numpy as np

import export_fit as ef
import rock_gen as rg

NL = chr(10)
T = chr(9)


def entry(name, slot, tile_m, params, h, ramp, mean_colour, gain, mottle):
    out = [T * 2 + '"%s": {' % name, T * 3 + '"slot": %s, "tile_cm": %.1f,' % (slot, float(tile_m) * 100)]
    out.append(T * 3 + '"params": PackedFloat32Array([')
    for i in range(0, len(rg.KEYS), 7):
        out.append(T * 4 + ", ".join("%.5f" % params.get(k, rg.PARAMS[k]) for k in rg.KEYS[i:i + 7]) + ",")
    out.append(T * 3 + "]),")
    out.append(T * 3 + '"height_range": Vector2(%.4f, %.4f),' % (float(h.min()), float(h.max())))
    out.append(T * 3 + '"ramp": [')
    for c in ramp:
        out.append(T * 4 + "Color(%.4f, %.4f, %.4f)," % tuple(c))
    out.append(T * 3 + "],")
    out.append(T * 3 + '"mean": Color(%.4f, %.4f, %.4f),' % tuple(mean_colour))
    out.append(T * 3 + '"gain": %.3f, "mottle": %.3f},' % (gain, mottle))
    return out


def main():
    folder, out = sys.argv[1], sys.argv[2]
    lines = ["# Generated by tools/bark/export_rock.py from the fits in tools/bark/fits: do not edit.",
             "class_name RockFits", "extends RefCounted", "",
             "## The fitted generators of the photographed rocks (parameters, height range, colour model)",
             "static func fits() -> Dictionary:", T + "return {"]
    for spec in sys.argv[3:]:
        name, tile_m, slot = spec.split(":")
        data = json.load(open(f"tools/bark/fits/{name}_rock.json"))
        params = {**rg.PARAMS, **data["params"]}
        cm = data["cm_per_px"]
        h = rg._render(512, cm, rg.vector(params), 1.0)
        photo = cv2.imread(f"{folder}/{name}_disp.png", cv2.IMREAD_UNCHANGED).astype(np.float32)
        if photo.ndim == 3:
            photo = photo.mean(axis=2)
        photo = (photo - photo.min()) / (photo.max() - photo.min())
        ramp = ef.palette_of(folder, name, photo)
        mean_colour, gain, mottle, contrast = ef.colour_model(folder, name, photo, cm)
        lift = ef.lift_of(mean_colour)
        ramp = [ef.lifted(c, lift) for c in ramp]
        mean_colour = ef.lifted(mean_colour, lift)
        print(name, "gain %.2f mottle %.3f lift x%.2f" % (gain, mottle, lift))
        lines += entry(name, slot, tile_m, params, h, ramp, mean_colour, gain, mottle)
    lines += [T + "}", "", "", "const KEYS := ["] + [T + '"%s",' % k for k in rg.KEYS] + ["]", ""]
    open(out, "w").write(NL.join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
